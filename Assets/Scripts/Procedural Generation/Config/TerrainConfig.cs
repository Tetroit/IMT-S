using System.Collections.Generic;
using UnityEngine;

namespace ProceduralGeneration
{
    public enum FlightPreviewMode
    {
        /// <summary>LOD falls off with distance to <see cref="TerrainConfig.center"/>.</summary>
        Radius,
        /// <summary>LOD falls off with distance to <see cref="TerrainConfig.path"/>.</summary>
        Path,
    }
    public enum DownloadMode
    {
        Single,
        Area
    }

    /// <summary>
    /// Mercator (EPSG:3857) to Unity conversion, Unity position = (mercator - origin) * scale.
    /// Also every SAT tile that has to be loaded, as Web Mercator XYZ tiles (used to retrieve the ArcGIS tiles),
    /// together with the settings they were generated from in the Flight Preview window.
    /// </summary>
    [CreateAssetMenu(menuName = "Procedural Generation/Terrain Config")]
    public class TerrainConfig : ScriptableObject
    {
        [Header("Geometry")]
        [Tooltip("Unity units per mercator unit.")]
        public double scale = 1.0;

        [Tooltip("Mercator coordinates (EPSG:3857, metres) that map to Unity (0, 0).")]
        public DoubleVector2 origin;

        public SatContext.SatContext originReference;

        [Header("Generation")]
        public FlightPreviewMode mode = FlightPreviewMode.Radius;
        public TileLodSettings lodSettings = TileLodSettings.Default;

        [Tooltip("Radius mode focus, mercator (EPSG:3857, metres).")]
        public DoubleVector2 center;

        [Tooltip("Path mode flight path nodes, mercator (EPSG:3857, metres).")]
        public List<DoubleVector2> path = new List<DoubleVector2>();

        [Header("Tiles")]
        [Tooltip("Tiles to load, coarse zoom first. Generated by Tools/Procedural Generation/Flight Preview.")]
        public List<TileBounds> tiles = new List<TileBounds>();

        [Header("Download properties")]
        public DownloadMode downloadMode;
        [Tooltip("Folder the files are written to, SatContext assets are only created inside Assets.")]
        public string downloadDstFolder;

        [Tooltip("Single mode: the tile to download.")]
        public TileBounds tileToDownload;
        [Tooltip("Single mode: zoom of color.png and segmentation_classes.tif.")]
        public int colorZoom;
        [Tooltip("Single mode: zoom of height.npy.")]
        public int heightZoom;

        [Tooltip("Area mode: preferred size of color.png and segmentation_classes.tif in pixels, lowered if the imagery has no zoom for it.")]
        public int colorResolution = 1024;
        [Tooltip("Area mode: preferred size of height.npy in pixels, lowered if the terrain has no zoom for it.")]
        public int heightResolution = 256;
        [Tooltip("Area mode: tiles whose files are already in the download folder are not requested again.")]
        public bool skipExisting = true;

        public DoubleVector2 MercatorToWorld(DoubleVector2 mercator) => (mercator - origin) * scale;

        /// <summary>
        /// Unity units per ground metre at the origin's latitude.
        /// </summary>
        public float GetMeterScale() => (float)(scale * WebMercator.MercatorPerMeter(origin.y));

        /// <summary>
        /// Sets origin to the center of <see cref="originReference"/> tile
        /// </summary>
        public void SetOriginAtContextReference()
        {
            double[] bounds = originReference.metadata.output.mercatorBoundsM;
            origin.x = (bounds[0] + bounds[2]) / 2;
            origin.y = (bounds[1] + bounds[3]) / 2;
        }

        public ILodFocus CreateFocus() => mode == FlightPreviewMode.Path
            ? new PathLodFocus(path)
            : new PointLodFocus(center);

        public TileLodBuilder.Result Generate() => TileLodBuilder.Build(lodSettings, CreateFocus());

        private void OnValidate()
        {
            lodSettings.Validate();
        }

        /// <summary>
        /// Blue for <paramref name="minZoom"/> to red for <paramref name="maxZoom"/>.
        /// </summary>
        public static Color GetZoomColor(int zoom, int minZoom, int maxZoom)
        {
            float t = maxZoom > minZoom ? Mathf.InverseLerp(minZoom, maxZoom, zoom) : 1;
            return Color.HSVToRGB(Mathf.Lerp(0.62f, 0f, t), 0.85f, 1f);
        }
    }
}
