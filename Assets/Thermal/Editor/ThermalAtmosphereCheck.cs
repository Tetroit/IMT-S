        [MenuItem("Thermal/Atmosphere Check")]
        static void Run()
        {
            int failed = 0, checks = 0;
            void Report(bool ok, string line)
            {
                checks++;
                if (ok) Debug.Log("[Atmosphere] " + line);
                else { failed++; Debug.LogError("[Atmosphere] " + line); }
            }

            var atmosphere = AssetDatabase.LoadAssetAtPath<ThermalAtmosphere>(k_Asset);
            string summary;
            if (atmosphere == null || !atmosphere.IsValid)
            {
                Report(false, $"no valid ThermalAtmosphere at {k_Asset}   FAIL");
                summary = "nothing checked";
            }
            else
            {
                summary = RunCore(atmosphere, Report);
                RunGpu(atmosphere, Report);
                RunScene(Report);
            }
            if (failed == 0)
                Debug.Log($"[Atmosphere] all {checks} checks passed: {summary}");
            else
                Debug.LogError($"[Atmosphere] {failed} of {checks} checks FAILED: {summary}");
        }

        /// <summary>Everything that needs no scene. Returns the summary line.</summary>
        internal static string RunCore(ThermalAtmosphere atmosphere, Action<bool, string> report)
        {
            // Transmission below the first u entry
            var got = new double[ThermalAtmosphere.SubBands];
            double worstShort = 0;
            foreach (string gas in new[] { "H2O lines", "CO2", "O3", "N2O", "CH4" })
            {
                int index = atmosphere.GasIndex(gas);
                double off = index < 0 ? double.PositiveInfinity : 0;
                foreach (var (name, u, tau) in k_Short)
                {
                    if (name != gas || index < 0)
                        continue;
                    atmosphere.Transmission(index, u, 1000, 290, 0.01, got);
                    for (int k = 0; k < 4; k++)
                        off = Worse(off, Math.Abs(got[k] - tau[k]));
                }
                worstShort = Math.Max(worstShort, off);
                bool ok = off <= k_ShortTolerance;
                report(ok, $"Transmission of {gas} below its first u entry, the linear limit: off by {E(off)}   {Ok(ok)}");
            }

            // H2O's continuum on its own (thermal-atmosphere/2): its table read by D, and its temperature factor
            double worstContinuum = double.PositiveInfinity;
            if (!atmosphere.HasContinuum)
                report(false, "the asset has no continuum table (thermal-atmosphere/2)   FAIL");
            else
            {
                worstContinuum = 0;
                foreach (var (d, tau) in k_Continuum)
                {
                    atmosphere.ContinuumTransmission(d, got);
                    for (int k = 0; k < 4; k++)
                        worstContinuum = Worse(worstContinuum, Math.Abs(got[k] - tau[k]));
                }
                foreach (var (t, f) in k_ContinuumFactor)
                    worstContinuum = Worse(worstContinuum, Math.Abs(atmosphere.ContinuumFactor(t) / f - 1));
                bool ok = worstContinuum <= k_ShortTolerance;
                report(ok, $"the continuum by D, {k_Continuum.Length} paths from 0 to past the table, and its f(T) at " +
                           $"{k_ContinuumFactor.Length} temperatures: off by {E(worstContinuum)}   {Ok(ok)}");
            }

            // AirAt
            double worstAir = 0;
            bool airMissing = false, marchMissing = false;
            for (int a = 0; a < k_Airs.Length && !airMissing; a++)
            {
                double off = 0;
                string at = "";
                try
                {
                    foreach (var (air, z, t, p, e) in k_Air)
                    {
                        if (air != a)
                            continue;
                        ThermalMath.AirAt(k_Airs[a], z, out double gt, out double gp, out double ge);
                        double d = Math.Max(Math.Abs(gt / t - 1), Math.Max(Math.Abs(gp / p - 1), Math.Abs(ge / e - 1)));
                        if (!(d <= off))
                            at = string.Format(CultureInfo.InvariantCulture, " (worst at {0} m: {1:F4} K, {2:F4} hPa, " +
                                               "{3:F5} hPa against {4:F4}, {5:F4}, {6:F5})", z, gt, gp, ge, t, p, e);
                        off = Worse(off, d);
                    }
                }
                catch (NotImplementedException)
                {
                    airMissing = true;
                    break;
                }
                worstAir = Math.Max(worstAir, off);
                bool ok = off <= k_AirTolerance;
                report(ok, $"AirAt, case {a}, 8 heights: off by {E(off)} relative{(ok ? "" : at)}   {Ok(ok)}");
            }
            if (airMissing)
                report(false, "ThermalMath.AirAt is not written yet   FAIL");

            // The standard upper air (step 5): ThermalUpperAir's lookup, then AirAbove's join
            double worstStandard = 0;
            foreach (var (summer, km, t, p, h2o, o3, trop) in k_Standard)
            {
                ThermalUpperAir.Standard(summer, km, out double gt, out double gp, out double gw, out double go);
                worstStandard = Worse(worstStandard, Math.Max(Math.Max(Math.Abs(gt / t - 1), Math.Abs(gp / p - 1)),
                    Math.Max(Math.Max(Math.Abs(gw / h2o - 1), Math.Abs(go / o3 - 1)),
                        Math.Abs(ThermalUpperAir.TropopauseKm(summer) / trop - 1))));
            }
            bool standardOk = worstStandard <= k_AirTolerance;
            report(standardOk, $"ThermalUpperAir.Standard, {k_Standard.Length} points over 4 seasons: off by " +
                               $"{E(worstStandard)} relative   {Ok(standardOk)}");

            double worstAbove = 0;
            bool aboveMissing = false;
            for (int a = 0; a < k_UpperAirs.Length && !aboveMissing; a++)
            {
                double off = 0;
                int heights = 0;
                string at = "";
                try
                {
                    foreach (var (air, z, t, p, e, o3) in k_UpperAir)
                    {
                        if (air != a)
                            continue;
                        heights++;
                        ThermalMath.AirAbove(k_UpperAirs[a], z, out double gt, out double gp, out double ge,
                            out double go);
                        double d = Math.Max(Math.Max(Math.Abs(gt / t - 1), Math.Abs(gp / p - 1)),
                            Math.Max(Math.Abs(ge / e - 1), Math.Abs(go / o3 - 1)));
                        if (!(d <= off))
                            at = string.Format(CultureInfo.InvariantCulture, " (worst at {0} m: {1:F4} K, {2:F4} hPa, " +
                                               "{3:G6} hPa, ozone {4:G6} against {5:F4}, {6:F4}, {7:G6}, {8:G6})", z, gt,
                                               gp, ge, go, t, p, e, o3);
                        off = Worse(off, d);
                    }
                }
                catch (NotImplementedException)
                {
                    aboveMissing = true;
                    break;
                }
                worstAbove = Math.Max(worstAbove, off);
                bool ok = off <= k_AirTolerance;
                report(ok, $"AirAbove, case {a} (summer {k_UpperAirs[a].summer:0.###}), {heights} heights: off by " +
                           $"{E(off)} relative{(ok ? "" : at)}   {Ok(ok)}");
            }
            if (aboveMissing)
                report(false, "ThermalMath.AirAbove is not written yet   FAIL");

            // MarchRay
            double worstTau = 0, worstPath = 0;
            int n = k_Ranges.Length;
            var tauRay = new double[n * 4];
            var pathRay = new double[n * 4];
            for (int a = 0; a < k_Airs.Length && !marchMissing; a++)
            {
                foreach (double height in new[] { 900.0, 2.0 })
                {
                    double offTau = 0, offPath = 0;
                    string at = "";
                    try
                    {
                        foreach (var (air, h, sine, tau, path) in k_Rays)
                        {
                            if (air != a || h != height)
                                continue;
                            Array.Clear(tauRay, 0, tauRay.Length);
                            Array.Clear(pathRay, 0, pathRay.Length);
                            ThermalMath.MarchRay(atmosphere, k_Airs[a], h, sine, k_Ranges, ThermalMath.SubBandIntegration,
                                                 tauRay, pathRay);
                            for (int k = 0; k < 4; k++)
                            {
                                offTau = Worse(offTau, Math.Abs(tauRay[k] - 1));
                                offPath = Worse(offPath, Math.Abs(pathRay[k]));
                            }
                            for (int q = 0; q < k_Kept.Length; q++)
                            {
                                int m = k_Kept[q];
                                for (int k = 0; k < 4; k++)
                                {
                                    double dt = Math.Abs(tauRay[m * 4 + k] - tau[q * 4 + k]);
                                    double dp = Math.Abs(pathRay[m * 4 + k] - path[q * 4 + k]);
                                    if (!(dt <= offTau) || !(dp <= offPath))
                                        at = string.Format(CultureInfo.InvariantCulture,
                                            " (worst near sin {0}, {1} m, sub-band {2}: τ {3:F9} against {4:F9}, " +
                                            "L {5:F7} against {6:F7})", sine, k_Ranges[m], k, tauRay[m * 4 + k],
                                            tau[q * 4 + k], pathRay[m * 4 + k], path[q * 4 + k]);
                                    offTau = Worse(offTau, dt);
                                    offPath = Worse(offPath, dp);
                                }
                            }
                        }
                    }
                    catch (NotImplementedException)
                    {
                        marchMissing = true;
                        break;
                    }
                    worstTau = Math.Max(worstTau, offTau);
                    worstPath = Math.Max(worstPath, offPath);
                    bool ok = offTau <= k_TauTolerance && offPath <= k_PathTolerance;
                    report(ok, string.Format(CultureInfo.InvariantCulture,
                        "MarchRay, case {0}, camera {1} m, 7 directions: τ off by {2}, L_path by {3} W/m²/sr{4}   {5}",
                        a, height, E(offTau), E(offPath), ok ? "" : at, Ok(ok)));
                }
            }
            if (marchMissing)
                report(false, "ThermalMath.MarchRay is not written yet   FAIL");

            // The table's layout, and a parallel build against a serial one
            double layout = 0;
            foreach (var (r, sine) in k_DirectionSines)
                layout = Worse(layout, Math.Abs(ThermalAtmosphereTable.DirectionSine(r) - sine));
            var nodes = new double[ThermalAtmosphereTable.Ranges];
            ThermalAtmosphereTable.RangeNodes(40000, nodes);
            foreach (var (m, range) in k_RangeNodes)
                layout = Worse(layout, Math.Abs(nodes[m] - range) / Math.Max(1, range));
            bool layoutOk = layout <= 1e-12;
            report(layoutOk, $"the table's directions and ranges against the reference's: off by {E(layout)}   {Ok(layoutOk)}");

            // The CPU's read of the table (ThermalAtmosphereTable.Lookup), which the GPU's must equal, on a table whose
            // entries encode their row, column and channel: every node returns its own entry, which ties the read to
            // the layout above, and between nodes the read is the code's linear function.
            float[] codedTau = Coded(true), codedPath = Coded(false);
            var tau4 = new double[4];
            var path4 = new double[4];
            double atNodes = 0;
            for (int r = 0; r < ThermalAtmosphereTable.Directions; r++)
            {
                double sine = ThermalAtmosphereTable.DirectionSine(r), cosine = Math.Sqrt(Math.Max(0, 1 - sine * sine));
                for (int c = 1; c < ThermalAtmosphereTable.Ranges; c++)   // range 0 has no direction
                {
                    ThermalAtmosphereTable.Lookup(codedTau, codedPath, 40000, nodes[c] * cosine, nodes[c] * sine, 0,
                                                  tau4, path4);
                    int at = (r * ThermalAtmosphereTable.Ranges + c) * 4;
                    for (int k = 0; k < 4; k++)
                    {
                        atNodes = Worse(atNodes, Math.Abs(tau4[k] - codedTau[at + k]));
                        atNodes = Worse(atNodes, Math.Abs(path4[k] - codedPath[at + k]));
                    }
                }
            }
            bool nodesOk = atNodes <= 1e-9;
            report(nodesOk, $"the CPU's read at each of the table's nodes, its own entry: off by {E(atNodes)}   {Ok(nodesOk)}");

            var random = new System.Random(20261030);
            double between = 0;
            for (int i = 0; i < 4000; i++)
            {
                double sine = 2 * random.NextDouble() - 1, cosine = Math.Sqrt(1 - sine * sine);
                double s = Math.Exp(Math.Log(0.1) + random.NextDouble() * (Math.Log(40000) - Math.Log(0.1)));
                ThermalAtmosphereTable.Lookup(codedTau, codedPath, 40000, s * cosine, s * sine, 0, tau4, path4);
                double row = (Math.Sign(sine) * Math.Sqrt(Math.Abs(sine)) + 1) / 2 * (ThermalAtmosphereTable.Directions - 1);
                double column = Math.Log(1 + s / ThermalAtmosphereTable.RangeScale) /
                                Math.Log(1 + 40000 / ThermalAtmosphereTable.RangeScale) * (ThermalAtmosphereTable.Ranges - 1);
                for (int k = 0; k < 4; k++)
                {
                    between = Worse(between, Math.Abs(tau4[k] - CodedValue(true, row, column, k)));
                    between = Worse(between, Math.Abs(path4[k] - CodedValue(false, row, column, k)));
                }
            }
            bool betweenOk = between <= 1e-9;
            report(betweenOk, $"the CPU's read between nodes, 4000 points: off the linear blend by {E(between)}   {Ok(betweenOk)}");

            if (!marchMissing)
            {
                var inputs = new ThermalAtmosphereTable.Inputs { air = k_Airs[0], cameraHeightM = 900, farM = 40000 };
                int size = ThermalAtmosphereTable.Directions * ThermalAtmosphereTable.Ranges * 4;
                float[] tauA = new float[size], pathA = new float[size], tauB = new float[size], pathB = new float[size];
                ThermalAtmosphereTable.Build(atmosphere, inputs, ThermalMath.SubBandIntegration, tauA, pathA, false);
                ThermalAtmosphereTable.Build(atmosphere, inputs, ThermalMath.SubBandIntegration, tauB, pathB, true);
                int differ = 0;
                for (int i = 0; i < size; i++)
                    if (BitConverter.SingleToInt32Bits(tauA[i]) != BitConverter.SingleToInt32Bits(tauB[i]) ||
                        BitConverter.SingleToInt32Bits(pathA[i]) != BitConverter.SingleToInt32Bits(pathB[i]))
                        differ++;
                string problem = ThermalAtmosphereTable.Problem(tauA, pathA);
                bool ok = differ == 0 && problem == null;
                report(ok, string.Format(CultureInfo.InvariantCulture,
                    "a table built in parallel against one built serially: {0} values differ{1}   {2}",
                    differ, problem == null ? "" : "; " + problem, Ok(ok)));
            }

            var notWritten = new List<string>();
            if (airMissing) notWritten.Add("AirAt");
            if (aboveMissing) notWritten.Add("AirAbove");
            if (marchMissing) notWritten.Add("MarchRay");
            string missing = notWritten.Count == 0 ? "" : $" ({string.Join(", ", notWritten)} not written yet)";
            return string.Format(CultureInfo.InvariantCulture,
                "short paths {0}; the continuum {1}; AirAt {2} relative; the upper air's standard {3}, AirAbove {4} " +
                "relative; MarchRay τ {5}, L_path {6} W/m²/sr{7}", E(worstShort), E(worstContinuum), E(worstAir),
                E(worstStandard), E(worstAbove), E(worstTau), E(worstPath), missing);
        }

        // The live environment's table: what is in its textures against a fresh build of what it says it was built for.
        static void RunScene(Action<bool, string> report)
        {
            var environment = UnityEngine.Object.FindAnyObjectByType<ThermalEnvironment>();
            if (environment == null || !environment.isActiveAndEnabled || environment.AtmosphereTable == null)
            {
                Debug.LogWarning("[Atmosphere] no enabled ThermalEnvironment in the scene: its table is not checked");
                return;
            }
            ThermalAtmosphereTable table = environment.AtmosphereTable;
            if (environment.Atmosphere == null)
            {
                Debug.LogWarning("[Atmosphere] the ThermalEnvironment has no atmosphere set: its table is not checked");
                return;
            }
            if (!table.HasTable)
            {
                Debug.LogWarning("[Atmosphere] the ThermalEnvironment has not taken a table yet" +
                                 (table.MarchIsPlaceholder ? " (MarchRay not written)" : "") + ": its table is not checked");
                return;
            }
            ThermalAtmosphereTable.Inputs inputs = table.BuiltInputs;
            int size = ThermalAtmosphereTable.Directions * ThermalAtmosphereTable.Ranges * 4;
            float[] tau = new float[size], path = new float[size];
            var clock = System.Diagnostics.Stopwatch.StartNew();
            ThermalAtmosphereTable.Build(environment.Atmosphere, inputs, environment.SubBandRadiance, tau, path, false);
            double serial = clock.Elapsed.TotalMilliseconds;
            clock.Restart();
            ThermalAtmosphereTable.Build(environment.Atmosphere, inputs, environment.SubBandRadiance, new float[size],
                                         new float[size], true);
            double parallel = clock.Elapsed.TotalMilliseconds;
            var tauTexture = table.Tau.GetPixelData<float>(0);
            var pathTexture = table.Path.GetPixelData<float>(0);
            int differ = 0;
            for (int i = 0; i < size; i++)
                if (BitConverter.SingleToInt32Bits(tau[i]) != BitConverter.SingleToInt32Bits(tauTexture[i]) ||
                    BitConverter.SingleToInt32Bits(path[i]) != BitConverter.SingleToInt32Bits(pathTexture[i]))
                    differ++;
            bool ok = differ == 0;
            report(ok, string.Format(CultureInfo.InvariantCulture,
                "the scene's table (camera {0:F2} m, air {1:F3} K, dew point {2:F3} K, ozone {3:F1} ppb, far {4:F0} m) " +
                "against a fresh build: {5} values differ   {6}", inputs.cameraHeightM, inputs.air.airTemperatureK,
                inputs.air.dewPointK, inputs.air.ozone * 1e9, inputs.farM, differ, Ok(ok)));
            Debug.Log(string.Format(CultureInfo.InvariantCulture, "[Atmosphere] building it here took {0:F0} ms serially " +
                                    "and {1:F0} ms with the directions in parallel", serial, parallel));
        }

        // Entries that encode where they are, exact in float: τ 0.25 k + c / 256 + r / 128, L 3 − 0.25 k + c / 128 − r / 64.
        // A read that swaps the rows and columns, flips the rows, mixes the channels or misplaces a weight is off by a
        // whole 1/256 or more.
        static float[] Coded(bool tau)
        {
            var a = new float[ThermalAtmosphereTable.Directions * ThermalAtmosphereTable.Ranges * 4];
            for (int r = 0; r < ThermalAtmosphereTable.Directions; r++)
                for (int c = 0; c < ThermalAtmosphereTable.Ranges; c++)
                    for (int k = 0; k < 4; k++)
                        a[(r * ThermalAtmosphereTable.Ranges + c) * 4 + k] = (float)CodedValue(tau, r, c, k);
            return a;
        }

        static double CodedValue(bool tau, double row, double column, int k) =>
            tau ? 0.25 * k + column / 256 + row / 128 : 3 - 0.25 * k + column / 128 - row / 64;

        // The GPU's read (ThermalAtmosphere.hlsl, as Thermal/Base runs it) against the CPU's, at points from straight
        // down to straight up, from the camera out past the last range.
        const string k_Shader = "Assets/Thermal/Editor/ThermalAtmosphereCheck.compute";
        const double k_GpuTauTolerance = 3e-5;     // the GPU's float row and column
        const double k_GpuPathTolerance = 3e-4;    // W/m²/sr, 0.01 NETD

        static void RunGpu(ThermalAtmosphere atmosphere, Action<bool, string> report)
        {
            var shader = AssetDatabase.LoadAssetAtPath<ComputeShader>(k_Shader);
            if (shader == null)
            {
                report(false, $"{k_Shader} is missing   FAIL");
                return;
            }
            int errors = 0;
            foreach (ShaderMessage m in ShaderUtil.GetComputeShaderMessages(shader))
            {
                if (m.severity != UnityEditor.Rendering.ShaderCompilerMessageSeverity.Error)
                    continue;
                errors++;
                Debug.LogError($"[Atmosphere] does not compile: {m.message} ({m.file}:{m.line})");
            }
            if (errors > 0)
            {
                report(false, "the GPU's read does not compile   FAIL");
                return;
            }

            float[] points = Points();
            int count = points.Length / 3;
            using var input = new ComputeBuffer(points.Length, sizeof(float));
            input.SetData(points);

            // The plumbing first, so a buffer fault never passes for a read fault.
            int echoKernel = shader.FindKernel("Echo");
            using (var echo = new ComputeBuffer(points.Length, sizeof(float)))
            {
                var nan = new float[points.Length];
                for (int i = 0; i < nan.Length; i++)
                    nan[i] = float.NaN;
                echo.SetData(nan);
                shader.SetBuffer(echoKernel, "_Points", input);
                shader.SetBuffer(echoKernel, "_Echo", echo);
                shader.SetInt("_Count", count);
                shader.Dispatch(echoKernel, (points.Length + 63) / 64, 1, 1);
                var got = new float[points.Length];
                echo.GetData(got);
                int differ = 0;
                for (int i = 0; i < points.Length; i++)
                    if (BitConverter.SingleToInt32Bits(got[i]) != BitConverter.SingleToInt32Bits(points[i]))
                        differ++;
                bool ok = differ == 0;
                report(ok, $"the check's own buffer: {points.Length - differ} of {points.Length} floats read back exactly   {Ok(ok)}");
                if (!ok)
                    return;
            }

            CompareGpu(shader, input, points, Coded(true), Coded(false), 40000,
                       "a table whose entries encode their row, column and channel", report);

            var inputs = new ThermalAtmosphereTable.Inputs { air = k_Airs[0], cameraHeightM = 900, farM = 40000 };
            int size = ThermalAtmosphereTable.Directions * ThermalAtmosphereTable.Ranges * 4;
            float[] tau = new float[size], path = new float[size];
            try
            {
                ThermalAtmosphereTable.Build(atmosphere, inputs, ThermalMath.SubBandIntegration, tau, path, true);
            }
            catch (NotImplementedException)
            {
                Debug.LogWarning("[Atmosphere] MarchRay is not written yet: the GPU's read of a marched table is not checked");
                return;
            }
            CompareGpu(shader, input, points, tau, path, 40000, "the march's table (case 0, camera 900 m, far 40 km)",
                       report);
        }

        static void CompareGpu(ComputeShader shader, ComputeBuffer input, float[] points, float[] tauTable,
                               float[] pathTable, double farM, string label, Action<bool, string> report)
        {
            int count = points.Length / 3;
            Texture2D tauTexture = NewTable(tauTable), pathTexture = NewTable(pathTable);
            var gotTau = new Vector4[count];
            var gotPath = new Vector4[count];
            try
            {
                int kernel = shader.FindKernel("Lookup");
                using var tauOut = new ComputeBuffer(count, 4 * sizeof(float));
                using var pathOut = new ComputeBuffer(count, 4 * sizeof(float));
                var nan = new Vector4[count];
                for (int i = 0; i < count; i++)
                    nan[i] = new Vector4(float.NaN, float.NaN, float.NaN, float.NaN);   // a read never written shows
                tauOut.SetData(nan);
                pathOut.SetData(nan);
                shader.SetBuffer(kernel, "_Points", input);
                shader.SetBuffer(kernel, "_TauOut", tauOut);
                shader.SetBuffer(kernel, "_PathOut", pathOut);
                shader.SetTexture(kernel, ThermalAtmosphereTable.TauName, tauTexture);
                shader.SetTexture(kernel, ThermalAtmosphereTable.PathName, pathTexture);
                shader.SetVector(ThermalAtmosphereTable.ParamsName, ThermalAtmosphereTable.Params(farM));
                shader.SetInt("_Count", count);
                shader.Dispatch(kernel, (count + 63) / 64, 1, 1);
                tauOut.GetData(gotTau);
                pathOut.GetData(gotPath);
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(tauTexture);
                UnityEngine.Object.DestroyImmediate(pathTexture);
            }

            var tau4 = new double[4];
            var path4 = new double[4];
            double offTau = 0, offPath = 0;
            string at = "";
            for (int i = 0; i < count; i++)
            {
                float x = points[i * 3], y = points[i * 3 + 1], z = points[i * 3 + 2];
                ThermalAtmosphereTable.Lookup(tauTable, pathTable, farM, x, y, z, tau4, path4);
                for (int k = 0; k < 4; k++)
                {
                    double dt = Math.Abs(gotTau[i][k] - tau4[k]), dp = Math.Abs(gotPath[i][k] - path4[k]);
                    if (!(dt <= offTau) || !(dp <= offPath))
                        at = string.Format(CultureInfo.InvariantCulture,
                            " (worst at ({0:G5}, {1:G5}, {2:G5}) m, sub-band {3}: GPU τ {4:G7}, L {5:G7}; CPU {6:G7}, {7:G7})",
                            x, y, z, k, gotTau[i][k], gotPath[i][k], tau4[k], path4[k]);
                    offTau = Worse(offTau, dt);
                    offPath = Worse(offPath, dp);
                }
            }
            bool ok = offTau <= k_GpuTauTolerance && offPath <= k_GpuPathTolerance;
            report(ok, string.Format(CultureInfo.InvariantCulture,
                "the GPU's read against the CPU's, {0}, {1} points: τ off by {2}, L_path by {3} W/m²/sr{4}   {5}", label,
                count, E(offTau), E(offPath), ok ? "" : at, Ok(ok)));
        }

        static Texture2D NewTable(float[] data)
        {
            var texture = new Texture2D(ThermalAtmosphereTable.Ranges, ThermalAtmosphereTable.Directions,
                                        TextureFormat.RGBAFloat, false, true)
            {
                hideFlags = HideFlags.HideAndDontSave,
                filterMode = FilterMode.Point,
                wrapMode = TextureWrapMode.Clamp,
            };
            texture.SetPixelData(data, 0);
            texture.Apply(false, false);
            return texture;
        }

        // Every kind of point the frag meets: the camera itself, straight down and up, level, past the last range, then
        // 2000 at random, half of them near the horizon, from 0.1 m to 60 km.
        static float[] Points()
        {
            var list = new List<float> { 0, 0, 0, 0, -900, 0, 0, 100, 0, 1000, 0, 0, 0, 0, 50000, 3, -2, 1 };
            var random = new System.Random(20261031);
            for (int i = 0; i < 2000; i++)
            {
                double u = 2 * random.NextDouble() - 1;
                double sine = i % 2 == 0 ? u : Math.Sign(u) * Math.Pow(Math.Abs(u), 4);
                double cosine = Math.Sqrt(1 - sine * sine), azimuth = 2 * Math.PI * random.NextDouble();
                double s = Math.Exp(Math.Log(0.1) + random.NextDouble() * (Math.Log(60000) - Math.Log(0.1)));
                list.Add((float)(s * cosine * Math.Cos(azimuth)));
                list.Add((float)(s * sine));
                list.Add((float)(s * cosine * Math.Sin(azimuth)));
            }
            return list.ToArray();
        }

        static double Worse(double worst, double d) => double.IsNaN(d) ? double.PositiveInfinity : Math.Max(worst, d);
        static string E(double x) => x.ToString("0.0e+0", CultureInfo.InvariantCulture);
        static string Ok(bool ok) => ok ? "ok" : "FAIL";
    }
